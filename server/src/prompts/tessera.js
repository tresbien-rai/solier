/**
 * Tessera base system layer
 *
 * A platform-level preamble prepended to every persona's system prompt. It
 * tells the model what Tessera is, that the text after it is a persona to
 * embody, and how the avatar expression protocol works.
 *
 * Why this lives server-side rather than in each persona's prompt text:
 *
 * - **It stays true.** The expression instruction is generated from the
 *   persona's *actual* expression set on every request. The old approach
 *   baked a hardcoded list ("neutral, happy, sad, ...") into each persona's
 *   saved prompt at creation, so adding or removing an expression never
 *   reached the model.
 * - **It can't be lost.** Editing a persona prompt can't delete it.
 * - **It caches well.** ORIENTATION is byte-identical for every user,
 *   persona, and conversation, so it sits at the front where it makes the
 *   longest shared prefix for provider prompt caching. The per-persona
 *   expression block comes after it, and the persona's own prompt last —
 *   most-shared to least-shared.
 */

/**
 * Reserved: the "working on it" state the UI drives while a response streams.
 * Never offered to the model. Note `thinking` is NOT reserved — it used to be
 * this slot, and is now an ordinary character expression (a hand-on-chin pose
 * is a perfectly good thing to declare).
 */
const RESERVED_EXPRESSIONS = new Set(['generating']);

// The preset layer (AP-01) supplies the override/normalisation rules and the
// macro expander. This module owns the TEXT; presets.js owns the SHAPE.
const { normalizeBlocks, expandMacros, buildMacroValues, isCustomBlockId } = require('./presets');
// The product name is interpolated from config rather than written here (BR-01)
// so a rename never has to touch prompt text. It is a per-deployment constant,
// so ORIENTATION stays byte-identical across requests and remains the shared
// cache prefix it was designed to be.
const config = require('../config');

/**
 * Expression names are interpolated into the system prompt, so they're
 * constrained. Deliberately matches `validateExpressionName` in
 * routes/avatars.js — names are also filenames and URL segments there, and a
 * name accepted here but rejected there would be an expression that can never
 * have art (spaces were exactly that bug).
 */
const VALID_EXPRESSION_NAME = /^[a-z0-9][a-z0-9_-]{0,30}$/i;
const MAX_EXPRESSIONS = 24;

/**
 * The constant platform environment preamble (DF-02).
 * Framed as `<operating_environment>` describing Solier without prescribing
 * generic-assistant behavior onto quirky or roleplay personas.
 */
const ORIENTATION = `<operating_environment>
# ${config.brand}
${config.brand} is a personal, infinite room that can be set up for anything; conversations, writing, work, and more. You'll share this space with the user as a character persona, through which your perceptions, speech, and even how you work will be processed.

Depending on the configuration of the session, you may be given access to various capabilities that can allow you to accomplish a variety of tasks. Use them freely as you see fit. When tools are available, earlier replies may include a \`<tool_trail>\` line generated by ${config.brand} summarizing tools that ran in that turn (their results aren't repeated, and don't write a \`<tool_trail>\` yourself).
</operating_environment>`;

/**
 * Filter a raw expression-name list down to what's safe and meaningful to
 * name in the system prompt.
 * @param {unknown} names - Expression names as supplied by the client
 * @returns {string[]} Valid, non-reserved, de-duplicated names
 */
function sanitizeExpressionNames(names) {
  if (!Array.isArray(names)) return [];
  const seen = new Set();
  const out = [];
  for (const raw of names) {
    if (typeof raw !== 'string') continue;
    const name = raw.trim();
    const key = name.toLowerCase();
    if (!VALID_EXPRESSION_NAME.test(name)) continue;
    if (RESERVED_EXPRESSIONS.has(key)) continue;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(name);
    if (out.length >= MAX_EXPRESSIONS) break;
  }
  return out;
}

/**
 * Protected `<capabilities>` sub-layer sections (DF-02).
 * Each sub-section is emitted ONLY when its capability is active for the
 * request, and the server wraps all active sub-sections automatically in
 * `<capabilities>...</capabilities>`.
 */
const CAPABILITIES_HEADER = `# Capabilities
This section lists what context, tools, and abilities you have access to in this session.`;

const CAPABILITY_WORKSPACE = `## Workspace & Project
Workspaces and Projects are specifically curated knowledge bases. A Workspace can contain several different Projects. Reference instructions and files from the active Workspace or Project are loaded at the start of the conversation.
\`<session_state>\` reflects current container and file counts.`;

const CAPABILITY_FILE_TOOLS = `## File Tools
Associated commands: {\`list_files\`, \`read_file\`, \`create_file\`, \`edit_file\`, \`move_file\`}

These File Tools commands allow you to inspect or modify file content. Call them directly rather than guessing file contents or claiming an edit you didn't run; if \`<session_state>\` reports files not shown in context, use \`list_files\` or \`read_file\`.`;

const SCRATCHPAD_SECTION = `## Scratchpad
Associated commands: {\`write_scratchpad\`, \`edit_scratchpad\`}

This is a live, shared space that sits beside the chat where both you and the user can freely make edits. It is best used for building upon and refining evolving work: drafts, plans, outlines, notes — updating it in place rather than appending a log (matching \`<current_content>\` verbatim for \`edit_scratchpad\`). Any changes made, with diff, are immediately visible to the user alongside any chat messages you send, so keep the chat itself brief rather than re-stating what went into the scratchpad.`;

const EXPRESSION_SECTION = `## Avatar Expressions
Associated commands: \`[expression: name]\`
List of available avatar expressions: {{expressions}}
Pick one tag from the list above (pick the closest match if none is exact), and place it once at the start of your final chat reply (not on tool-use turns). ${config.brand} strips the tag before display, so never mention it.`;

/**
 * The user-profile block (UP-03, DF-02).
 * Placed at the start of the Message layer by default (before Conversation
 * History, still inside the cached prefix), or in the System layer if a preset
 * moves it there. Drops `"trust the conversation"` so personas can naturally
 * notice contradictions (and later update memory).
 */
const PROFILE_SECTION = `<user_profile>
# User: {{user}}
This is background context you already know about the user. It should be used quietly, and not recited back or brought up unprompted.

{{profile}}
</user_profile>`;

/**
 * The synthetic assistant turn that acknowledges leading context (`<user_profile>`
 * and/or Workspace/Project KB). Kept maximally voice-neutral so it never primes
 * third-person, archaic, or quirky personas into casual chatbot register (DF-02).
 */
const CONTEXT_ACK = 'Reference context noted.';

/** Built-in text for every editable block, by id. */
const BUILTIN_BLOCK_TEXT = {
  orientation: ORIENTATION,
  profile: PROFILE_SECTION,
  context_ack: CONTEXT_ACK,
};

/**
 * Metadata + server-owned wording for each sub-section inside `<capabilities>`.
 * Exposed via GET /api/presets/defaults so the Preset Editor can show users
 * exactly what the protected sub-layer contains without duplicating strings.
 */
const CAPABILITY_SECTIONS = [
  {
    id: 'workspace',
    title: 'Workspace & Project',
    condition: 'Active when this chat belongs to a Workspace or Project',
    text: CAPABILITY_WORKSPACE,
  },
  {
    id: 'file_tools',
    title: 'File Tools',
    condition: 'Active when File Tools are turned on for this chat',
    text: CAPABILITY_FILE_TOOLS,
  },
  {
    id: 'scratchpad',
    title: 'Scratchpad',
    condition: 'Active when the Scratchpad is enabled for this chat',
    text: SCRATCHPAD_SECTION,
  },
  {
    id: 'expressions',
    title: 'Avatar Expressions',
    condition: 'Active when the persona has expressions and Aux Expressions is off',
    text: EXPRESSION_SECTION,
  },
];

/** The text a block renders with: the preset's override, or the built-in. */
function blockText(preset, id) {
  const override = preset.blocks[id] && preset.blocks[id].text;
  return typeof override === 'string' ? override : (BUILTIN_BLOCK_TEXT[id] || '');
}

/**
 * Render the protected `<capabilities>` sub-layer from active request features.
 * Returns '' when zero capabilities are active so no empty wrapper is emitted.
 */
function buildCapabilitiesBlock(expressionNames, options = {}, macros = null) {
  const names = sanitizeExpressionNames(expressionNames);
  const resolvedMacros = macros || buildMacroValues({ ...(options.macros || {}), expressionNames: names });
  const sections = [];

  if (options.hasContainer) sections.push(CAPABILITY_WORKSPACE);
  if (options.toolsEnabled) sections.push(CAPABILITY_FILE_TOOLS);
  if (options.scratchpad) sections.push(SCRATCHPAD_SECTION);
  if (names.length > 0 && !options.auxExpressions) {
    sections.push(expandMacros(EXPRESSION_SECTION, resolvedMacros).trim());
  }

  if (sections.length === 0) return '';
  return `<capabilities>\n${CAPABILITIES_HEADER}\n\n${sections.join('\n\n')}\n</capabilities>`;
}

/**
 * Render the `<main_persona>` span wrapping the persona's assembled prompt with
 * its name (`# Persona: {{char}}`) and an explicit closing tag (DF-02).
 */
function wrapPersonaBlock(personaText, charName) {
  const cleanName = typeof charName === 'string' ? charName.trim() : '';
  const heading = cleanName ? `# Persona: ${cleanName}` : '# Persona';
  return `<main_persona>\n${heading}\nThis is who you are.\n\n${personaText}\n</main_persona>`;
}

/**
 * Render and evaluate the `profile` block (shared by System-layer and
 * Message-layer placement so gating & provenance stay in one place).
 */
function evaluateProfileBlock(preset, macros, options = {}) {
  const block = preset.blocks.profile;
  if (!block || !block.enabled) {
    return { id: 'profile', included: false, reason: 'disabled', chars: 0 };
  }
  if (!options.profileEnabled) {
    return { id: 'profile', included: false, reason: 'profile-off', chars: 0 };
  }
  const hasContent = Boolean(macros.profile || options.hasProfile);
  if (!hasContent) {
    return { id: 'profile', included: false, reason: 'no-profile', chars: 0 };
  }
  const overridden = typeof block.text === 'string';
  let text = expandMacros(blockText(preset, 'profile'), macros).trim();
  // Clean up empty `# User:` trailing space or trailing blank lines when name-only
  text = text
    .replace(/^# User:\s*$/m, '# User')
    .replace(/\n{2,}(<\/user_profile>)/g, '\n$1');
  if (!text) {
    return { id: 'profile', included: false, reason: 'empty', chars: 0 };
  }
  return {
    id: 'profile',
    included: true,
    source: overridden ? 'preset' : 'built-in',
    chars: text.length,
    text,
  };
}

/** Whether `profile` is placed in the System layer for this preset (default: false = Message layer). */
function isProfileInSystemLayer(options = {}) {
  const preset = normalizeBlocks(options.preset);
  return preset.blocks.profile?.layer === 'system';
}

/**
 * Build the `<user_profile>` text for the Message layer (returns '' when
 * `profile` is placed in System, disabled, opted out, or empty).
 */
function buildProfileMessageBlock(options = {}) {
  if (isProfileInSystemLayer(options)) return '';
  const preset = normalizeBlocks(options.preset);
  const macros = buildMacroValues(options.macros || {});
  const res = evaluateProfileBlock(preset, macros, options);
  return res.included ? res.text : '';
}

/** Shared evaluation for `persona` (works in System or Message layer). */
function evaluatePersonaBlock(preset, personaPrompt, macros) {
  const block = preset.blocks.persona;
  if (!block || !block.enabled) {
    return { id: 'persona', included: false, reason: 'disabled', chars: 0 };
  }
  const persona = typeof personaPrompt === 'string' ? personaPrompt.trim() : '';
  if (!persona) {
    return { id: 'persona', included: false, reason: 'no-persona-prompt', chars: 0 };
  }
  const span = wrapPersonaBlock(persona, macros.char);
  return { id: 'persona', included: true, source: 'persona', chars: span.length, text: span };
}

/** Shared evaluation for a custom user-added preset block (`custom_*`). */
function evaluateCustomBlock(id, block, macros) {
  const name = block?.name || id;
  if (!block || !block.enabled) {
    return { id, name, custom: true, included: false, reason: 'disabled', chars: 0 };
  }
  const text = expandMacros(typeof block.text === 'string' ? block.text : '', macros).trim();
  if (!text) {
    return { id, name, custom: true, included: false, reason: 'empty', chars: 0 };
  }
  return { id, name, custom: true, included: true, source: 'preset', chars: text.length, text };
}

/**
 * Compose Message-layer leading cached blocks (everything in `preset.messageOrder`
 * except volatile tail custom blocks): `<user_profile>`, `<main_persona>` when
 * moved to Message, and custom blocks with `placement === 'cached'`.
 *
 * @returns {{ texts: string[], blocks: Array<Object> }}
 */
function composeMessageLeadingBlocks(personaPrompt, options = {}) {
  const preset = normalizeBlocks(options.preset);
  const rawExpr = options.expressionNames !== undefined ? options.expressionNames : options.macros?.expressionNames;
  const macros = buildMacroValues({ ...(options.macros || {}), expressionNames: sanitizeExpressionNames(rawExpr) });
  const texts = [];
  const blocks = [];

  for (const id of preset.messageOrder) {
    const block = preset.blocks[id];
    if (!block) continue;

    if (id === 'profile') {
      if (block.layer === 'system') continue;
      const res = { ...evaluateProfileBlock(preset, macros, options), layer: 'message' };
      blocks.push(res);
      if (res.included) texts.push(res.text);
      continue;
    }

    if (id === 'persona') {
      if (block.layer !== 'message') continue;
      const res = { ...evaluatePersonaBlock(preset, personaPrompt, macros), layer: 'message' };
      blocks.push(res);
      if (res.included) texts.push(res.text);
      continue;
    }

    if (isCustomBlockId(id) && block.layer === 'message' && block.placement !== 'tail') {
      const res = { ...evaluateCustomBlock(id, block, macros), layer: 'message', placement: 'cached' };
      blocks.push(res);
      if (res.included) texts.push(res.text);
    }
  }
  return { texts, blocks };
}

/**
 * Compose Message-layer volatile tail custom blocks (`placement === 'tail'`),
 * injected alongside `<current_context>` on the latest user message.
 *
 * @returns {{ texts: string[], blocks: Array<Object> }}
 */
function composeMessageTailBlocks(options = {}) {
  const preset = normalizeBlocks(options.preset);
  const rawExpr = options.expressionNames !== undefined ? options.expressionNames : options.macros?.expressionNames;
  const macros = buildMacroValues({ ...(options.macros || {}), expressionNames: sanitizeExpressionNames(rawExpr) });
  const texts = [];
  const blocks = [];

  for (const id of preset.messageOrder) {
    const block = preset.blocks[id];
    if (!block || !isCustomBlockId(id)) continue;
    if (block.layer !== 'message' || block.placement !== 'tail') continue;
    const res = { ...evaluateCustomBlock(id, block, macros), layer: 'message', placement: 'tail' };
    blocks.push(res);
    if (res.included) texts.push(res.text);
  }
  return { texts, blocks };
}

/** Provenance entry for Message-layer `profile` (AP-05). Returns null if `profile` was moved to System. */
function describeProfileMessageBlock(options = {}) {
  if (isProfileInSystemLayer(options)) return null;
  const preset = normalizeBlocks(options.preset);
  const macros = buildMacroValues(options.macros || {});
  return { ...evaluateProfileBlock(preset, macros, options), layer: 'message' };
}

/**
 * Compose the full system prompt for a provider call.
 *
 * Blocks render in the preset's order, joined by a blank line. Three of them are
 * CONDITIONAL on things the preset does not control (D3): the expression section
 * needs the persona to actually have expressions, the scratchpad section needs
 * the pad to be active for this request, and the persona block needs the persona
 * to have a prompt. A preset can reword or reorder them; it cannot make one
 * appear when its condition is false.
 *
 * With no preset this is byte-identical to the pre-AP-01 output — see
 * prompts/test-presets.js, which pins that against a golden string.
 *
 * @param {string} [personaPrompt] - The persona's own system prompt
 * @param {unknown} [expressionNames] - The persona's expression names, unsanitized
 * @param {Object} [options]
 * @param {boolean} [options.scratchpad] - the scratchpad is active for this request (SP-05)
 * @param {boolean} [options.profileEnabled] - the persona may see the user profile (UP-03)
 * @param {boolean} [options.auxExpressions] - aux model picks expressions, so omit tag instructions from main prompt
 * @param {Object} [options.preset] - resolved preset blocks; omit for the built-in layer
 * @param {Object} [options.macros] - buildMacroValues() input (persona name, model, …)
 * @returns {string} The assembled system prompt
 */
function buildSystemPrompt(personaPrompt, expressionNames, options = {}) {
  return composeSystemPrompt(personaPrompt, expressionNames, options).text;
}

/**
 * The composer behind buildSystemPrompt, with provenance (AP-05).
 *
 * Returns the same text plus a record of every block: whether it was included,
 * where its text came from, how big it was, and — the useful part when a prompt
 * isn't doing what you expect — WHY a block was left out. buildSystemPrompt is
 * a thin wrapper over this rather than a parallel implementation, so the
 * inspector can never describe an assembly that differs from the real one.
 *
 * `source`: 'preset' (an override), 'built-in', or 'persona' (the persona's own
 * prompt). `reason` on an excluded block is a stable code the client turns into
 * a sentence: disabled | no-expressions | aux-expressions | scratchpad-inactive | no-persona-prompt | empty.
 *
 * @returns {{text: string, blocks: Array<Object>}}
 */
function composeSystemPrompt(personaPrompt, expressionNames, options = {}) {
  const preset = normalizeBlocks(options.preset);
  const names = sanitizeExpressionNames(expressionNames);
  // expressionNames is forced from the sanitized list: the macro must describe
  // the persona's real expression set, never whatever a caller passed in.
  const macros = buildMacroValues({ ...(options.macros || {}), expressionNames: names });

  const parts = [];
  const blocks = [];
  const skip = (id, reason) => blocks.push({ id, layer: 'system', included: false, reason, chars: 0 });

  for (const id of preset.order) {
    const block = preset.blocks[id];

    // Legacy message/sub-layer ids can never enter the system prompt directly.
    if (id === 'state' || id === 'expressions' || id === 'scratchpad') continue;

    if (id === 'profile') {
      // Only rendered in System when explicitly placed there by the preset.
      if (block?.layer !== 'system') continue;
      const res = evaluateProfileBlock(preset, macros, options);
      blocks.push({ ...res, layer: 'system' });
      if (res.included) parts.push(res.text);
      continue;
    }

    if (id === 'capabilities') {
      const capText = buildCapabilitiesBlock(names, options, macros);
      if (!capText) {
        skip('capabilities', 'no-capabilities');
        continue;
      }
      parts.push(capText);
      blocks.push({ id: 'capabilities', layer: 'system', included: true, source: 'built-in', chars: capText.length, text: capText });
      continue;
    }

    if (id === 'persona') {
      if (block?.layer === 'message') continue;
      const res = evaluatePersonaBlock(preset, personaPrompt, macros);
      blocks.push({ ...res, layer: 'system' });
      if (res.included) parts.push(res.text);
      continue;
    }

    if (isCustomBlockId(id)) {
      if (!block || block.layer !== 'system') continue;
      const res = evaluateCustomBlock(id, block, macros);
      blocks.push({ ...res, layer: 'system' });
      if (res.included) parts.push(res.text);
      continue;
    }

    if (!block || !block.enabled) {
      skip(id, 'disabled');
      continue;
    }

    const overridden = typeof preset.blocks[id].text === 'string';
    const text = expandMacros(blockText(preset, id), macros).trim();
    if (!text) {
      skip(id, 'empty');
      continue;
    }
    parts.push(text);
    blocks.push({
      id,
      layer: 'system',
      included: true,
      source: overridden ? 'preset' : 'built-in',
      chars: text.length,
      text,
    });
  }
  return { text: parts.join('\n\n'), blocks };
}

/**
 * The context acknowledgement text for this request (see CONTEXT_ACK).
 * @param {Object} [options] - { preset, macros }, as buildSystemPrompt takes
 * @returns {string} the ack, or '' when the block is disabled
 */
function buildContextAck(options = {}) {
  const preset = normalizeBlocks(options.preset);
  if (!preset.blocks.context_ack.enabled) return '';
  return expandMacros(blockText(preset, 'context_ack'), buildMacroValues(options.macros || {})).trim();
}

/**
 * The context-ack block's provenance entry (AP-05), in the same shape
 * composeSystemPrompt produces. It lives in the MESSAGE layer, so it is
 * described separately rather than appearing in the system-prompt list.
 *
 * @param {Object} [options] - { preset, macros }, as buildContextAck takes
 * @param {boolean} [hasContext] - whether this request injects KB context at all
 */
function describeContextAck(options = {}, hasContext = false) {
  const preset = normalizeBlocks(options.preset);
  const id = 'context_ack';
  if (!preset.blocks[id].enabled) return { id, layer: 'message', included: false, reason: 'disabled', chars: 0 };
  if (!hasContext) return { id, layer: 'message', included: false, reason: 'no-context', chars: 0 };
  const text = buildContextAck(options);
  if (!text) return { id, layer: 'message', included: false, reason: 'empty', chars: 0 };
  return {
    id,
    layer: 'message',
    included: true,
    source: typeof preset.blocks[id].text === 'string' ? 'preset' : 'built-in',
    chars: text.length,
    text,
  };
}

/**
 * The `<session_state>` block as it goes into the MESSAGE layer (PC-01).
 *
 * A pass-through of what buildSessionState produced, trimmed — the text is
 * generated from live state and a preset may neither reword nor suppress it
 * (docs/design/SESSION_STATE_DESIGN.md, D3), so unlike every other block there is
 * nothing here to override. It exists as a named function so the send path and
 * the inspector reach the block the same way, and so the "which layer does this
 * live in" answer is in one place.
 *
 * @param {Object} [options] - the promptOptions the assembly built
 * @returns {string} the block, or '' when there is no state to report
 */
function sessionStateBlock(options = {}) {
  return typeof options.sessionState === 'string' ? options.sessionState.trim() : '';
}

/** Whether `<current_context>` is placed `'before'` (default) or `'after'` the latest user message (DF-03). */
function resolveStatePosition(options = {}) {
  const preset = normalizeBlocks(options.preset);
  return preset.blocks.state?.position === 'after' ? 'after' : 'before';
}

/**
 * The session-state block's provenance entry (AP-05), in the same shape
 * composeSystemPrompt produces. Mirrors describeContextAck: a message-layer
 * block is described separately rather than appearing in the system-prompt
 * list.
 *
 * `source: 'generated'` is carried over from when this was a system block, so
 * the inspector keeps labelling it the same way.
 *
 * @param {Object} [options] - the promptOptions the assembly built
 */
function describeSessionState(options = {}) {
  const id = 'state';
  const position = resolveStatePosition(options);
  const text = sessionStateBlock(options);
  if (!text) {
    return {
      id,
      layer: 'message',
      position,
      included: false,
      reason: options.bareChat ? 'bare-chat' : 'no-session-state',
      chars: 0,
    };
  }
  return { id, layer: 'message', position, included: true, source: 'generated', chars: text.length, text };
}

